// Package clock предоставляет нейтральный контракт времени и рабочую
// реализацию для системных часов. Пакет не знает модули и их предметные правила.
package clock

import "time"

// Clock предоставляет текущее время Go для управляемых решений владельца.
// Реализацию передает composition root или тест, поэтому код не фиксирует
// источник времени.
type Clock interface {
	// Now возвращает текущее время Go для динамических проверок операции.
	Now() time.Time
}

// RealTime возвращает текущее системное время; нулевое значение готово к использованию.
type RealTime struct{}

// Now получает время при вызове, а не при создании часов или получении HTTP-запроса.
func (RealTime) Now() time.Time {
	return time.Now()
}
