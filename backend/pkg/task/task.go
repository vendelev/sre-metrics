// Package task публикует результат фоновой задачи владельцу остановки.
// Пакет не запускает горутин: владелец задачи сам запускает функцию и
// вызывает Complete один раз.
package task

import (
	"sync"
)

// Task публикует результат фонового задания закрытием Done. После истечения
// бюджета остановки владелец не ждёт произвольную Go-функцию и не читает
// ещё не готовый результат.
type Task struct {
	done     chan struct{}
	err      error // Читается только после закрытия done.
	complete sync.Once
}

// New создает задачу до запуска связанной горутины.
func New() *Task {
	return &Task{done: make(chan struct{})}
}

// Done закрывается при завершении задания; повторных закрытий нет.
func (t *Task) Done() <-chan struct{} {
	return t.done
}

// Err возвращает результат завершённого задания. Вызывать только после
// закрытия Done, включая конкурентное чтение: до него значение не готово.
func (t *Task) Err() error {
	return t.err
}

// Complete публикует результат задания и закрывает Done. Вызывает владелец
// задачи один раз; повторный вызов безопасен и не заменяет первый результат.
func (t *Task) Complete(err error) {
	t.complete.Do(func() {
		t.err = err
		close(t.done)
	})
}
