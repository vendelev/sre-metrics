// Package fileinbox читает обычные файлы <uuid>.json из одного Unix-каталога.
// Отправитель публикует неизменяемый файл переименованием из временного
// файла в том же каталоге. Имя содержит UUID в каноническом нижнем регистре;
// пакет не разбирает содержимое. Каждый каталог обслуживает один Inbox.
//
// После успешного Handle Inbox удаляет файл; после окончательного отказа
// он тоже его удаляет. Исчезновение файла не подтверждает приём, обработку
// или доставку события. Состояние повторов хранится только до остановки:
// сбой между успешным Handle и удалением допускает повтор после рестарта.
//
// Путь каталога должен оставаться стабильным. Удаление сравнивает текущую
// запись с обработанной, но Unix не даёт атомарно проверить inode и удалить
// имя: замена между последней проверкой и unlink всё ещё возможна.
