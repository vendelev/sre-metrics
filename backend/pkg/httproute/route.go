// Package httproute описывает сборку приложения из публичных HTTP-маршрутов
// функциональных модулей. Пакет не знает модули, не открывает сетевых
// ресурсов и не запускает сервер.
package httproute

import "net/http"

// Route описывает смонтированный в корневой маршрутизатор приложения
// обработчик модуля. Prefix задает префикс маршрутизации, а обработчик
// модуля регистрирует собственные пути относительно этого префикса.
type Route struct {
	Prefix  string
	Handler http.Handler
}
