// Package web содержит общие HTTP-типы сборки приложения из модулей.
// Пакет не знает функциональные модули и не открывает сетевых ресурсов.
package web

import "net/http"

// Route описывает смонтированный в корневой маршрутизатор приложения
// обработчик модуля. Prefix задает префикс маршрутизации, а обработчик
// модуля регистрирует собственные пути относительно этого префикса.
type Route struct {
	Prefix  string
	Handler http.Handler
}
