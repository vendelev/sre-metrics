package contract

import "time"

// Clock предоставляет текущее время Go. Операция вызывает Now после входа в Within.
// Реализация не должна выполнять длительный ввод-вывод или обращаться к тому же Store.
type Clock interface {
	// Now возвращает текущее время Go для динамических проверок операции.
	Now() time.Time
}
